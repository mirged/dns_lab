#!/usr/bin/env bash
# Run two dns_lab instances against each other on one machine.
#
# Two directories' worth of config is not much, but every field matters: both
# nodes need the same `zone` and `shared_key` (they derive the routing tag from
# them), a different `node_id`, a different `listen_addr`, separate databases,
# and each `[[peers]] addr` pointing at the *other* node's listener. Get one of
# those wrong and the GUI opens fine but nothing is ever delivered.
#
# Usage:
#   scripts/local_pair.sh up       # write configs if missing, start both GUIs
#   scripts/local_pair.sh down     # stop both GUIs
#   scripts/local_pair.sh status   # pids, listening ports, last messages
#   scripts/local_pair.sh test     # headless end-to-end check of the same configs
#   scripts/local_pair.sh config   # only (re)write the configs
#   scripts/local_pair.sh reset    # down + delete databases and downloads
#   scripts/local_pair.sh logs [alice|bob]
#
# Environment overrides:
#   DNS_LAB_BIN        binary to run          (default: target/release/dns_lab)
#   DNS_LAB_PAIR_DIR   state directory        (default: ~/dns-lab-local)
#   DNS_LAB_PAIR_PORT  first of two ports     (default: 16000, bob gets +1)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN="${DNS_LAB_BIN:-$ROOT/target/release/dns_lab}"
DIR="${DNS_LAB_PAIR_DIR:-$HOME/dns-lab-local}"
BASE_PORT="${DNS_LAB_PAIR_PORT:-16000}"

ALICE_ADDR="127.0.0.1:$BASE_PORT"
BOB_ADDR="127.0.0.1:$((BASE_PORT + 1))"
ALICE_ID="aaaa1111"
BOB_ID="bbbb2222"
ZONE="lab.local"

pid_file() { printf '%s/%s.pid' "$DIR" "$1"; }
log_file() { printf '%s/%s.log' "$DIR" "$1"; }

die() { printf '[!] %s\n' "$*" >&2; exit 1; }
say() { printf '[*] %s\n' "$*"; }

need_bin() {
  [ -x "$BIN" ] || die "no binary at $BIN - run 'cargo build --release' first"
}

port_busy() {
  ss -lunH "sport = :$1" 2>/dev/null | grep -q . || ss -ltnH "sport = :$1" 2>/dev/null | grep -q .
}

running() {
  local pf; pf="$(pid_file "$1")"
  [ -f "$pf" ] || return 1
  local pid; pid="$(cat "$pf" 2>/dev/null || true)"
  [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null
}

key() {
  local kf="$DIR/shared.key"
  if [ ! -s "$kf" ]; then
    mkdir -p "$DIR"
    openssl rand -base64 32 | tr -d '\n' > "$kf"
    chmod 600 "$kf"
  fi
  cat "$kf"
}

# One config per node. Relative db_path/download_dir resolve next to the config
# file, which is exactly what we want here: everything stays in $DIR.
write_config() {
  local name=$1 id=$2 addr=$3 peer_id=$4 peer_addr=$5 shared=$6
  cat > "$DIR/$name.toml" <<EOF
# dns_lab local pair - $name. Generated by scripts/local_pair.sh; safe to edit.
# The only hard rules: same zone + shared_key as the peer, different node_id,
# listen_addr and db_path, and a [[peers]] addr that is the *peer's* listener.
display_name = "$name"
node_id      = "$id"
listen_addr  = "$addr"
zone         = "$ZONE"
egress       = "direct"
# One host needs neither a relay nor a domain.
poll_interval_secs = 1
# 4 KiB replies: voice packets are ~500 bytes each and a press should not be
# chopped across three polls on loopback.
edns_udp_size = 4096
window = 8
shared_key   = "$shared"
db_path      = "$name.db"
download_dir = "downloads-$name"

[[peers]]
id   = "$peer_id"
name = "$( [ "$name" = alice ] && echo bob || echo alice )"
addr = "$peer_addr"
via  = "direct"
EOF
}

cmd_config() {
  mkdir -p "$DIR"
  local shared; shared="$(key)"
  if [ -f "$DIR/alice.toml" ] || [ -f "$DIR/bob.toml" ]; then
    say "configs already exist in $DIR (kept; delete them to regenerate)"
  else
    write_config alice "$ALICE_ID" "$ALICE_ADDR" "$BOB_ID" "$BOB_ADDR" "$shared"
    write_config bob   "$BOB_ID"   "$BOB_ADDR"   "$ALICE_ID" "$ALICE_ADDR" "$shared"
    say "wrote $DIR/alice.toml and $DIR/bob.toml"
  fi
  chmod 600 "$DIR/alice.toml" "$DIR/bob.toml" 2>/dev/null || true
}

start_one() {
  local name=$1
  running "$name" && { say "$name already running (pid $(cat "$(pid_file "$name")"))"; return 0; }
  : > "$(log_file "$name")"
  nohup "$BIN" "$MODE" --config "$DIR/$name.toml" >> "$(log_file "$name")" 2>&1 &
  echo $! > "$(pid_file "$name")"
}

cmd_up() {
  need_bin
  [ -n "${DISPLAY:-}${WAYLAND_DISPLAY:-}" ] || die "no display: use '$0 test' for a headless check"
  cmd_config
  for p in "${ALICE_ADDR##*:}" "${BOB_ADDR##*:}"; do
    if port_busy "$p" && ! running alice && ! running bob; then
      die "udp/tcp port $p is already in use; stop that process or set DNS_LAB_PAIR_PORT"
    fi
  done
  MODE=gui
  start_one alice
  start_one bob
  # Wait for both listeners to answer, then report what the GUI is showing.
  for _ in $(seq 1 40); do
    if port_busy "${ALICE_ADDR##*:}" && port_busy "${BOB_ADDR##*:}"; then break; fi
    sleep 0.25
  done
  for n in alice bob; do
    if running "$n"; then
      say "$n up (pid $(cat "$(pid_file "$n")"), $( [ "$n" = alice ] && echo "$ALICE_ADDR" || echo "$BOB_ADDR" ))"
    else
      printf '[!] %s exited; last log lines:\n' "$n" >&2
      tail -n 15 "$(log_file "$n")" >&2 || true
      exit 1
    fi
  done
  echo
  echo "Two windows should be on screen. Chat freely: both contacts are already in the list."
  echo "Stop them with: $0 down"
}

cmd_down() {
  local any=0
  for n in alice bob; do
    local pf; pf="$(pid_file "$n")"
    if [ -f "$pf" ]; then
      local pid; pid="$(cat "$pf" 2>/dev/null || true)"
      if [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null; then
        kill "$pid" 2>/dev/null || true
        any=1
      fi
      rm -f "$pf"
    fi
  done
  # Belt and braces: a GUI started by hand from the same directory.
  if pgrep -f "dns_lab gui --config $DIR/" >/dev/null 2>&1; then
    pkill -f "dns_lab gui --config $DIR/" || true
    any=1
  fi
  # Give the sockets a moment to be released before a following `up`.
  for _ in $(seq 1 20); do
    port_busy "${ALICE_ADDR##*:}" || port_busy "${BOB_ADDR##*:}" || break
    sleep 0.1
  done
  [ "$any" = 1 ] && say "stopped" || say "nothing running"
}

cmd_status() {
  for n in alice bob; do
    local addr; addr="$( [ "$n" = alice ] && echo "$ALICE_ADDR" || echo "$BOB_ADDR" )"
    local p="${addr##*:}"
    if running "$n"; then
      printf '%-6s up    pid %-7s listen %-18s port %s\n' "$n" "$(cat "$(pid_file "$n")")" "$addr" \
        "$(port_busy "$p" && echo bound || echo FREE)"
    else
      printf '%-6s down  %-11s listen %-18s port %s\n' "$n" "" "$addr" \
        "$(port_busy "$p" && echo BUSY || echo free)"
    fi
  done
  [ -x "$BIN" ] || return 0
  for n in alice bob; do
    [ -f "$DIR/$n.toml" ] || continue
    echo
    echo "--- $n ---"
    "$BIN" id --config "$DIR/$n.toml" 2>&1 | sed 's/^/  /'
    "$BIN" inbox --config "$DIR/$n.toml" --limit 3 2>&1 | sed 's/^/  /'
  done
}

# Headless proof that the pair actually exchanges mail: both nodes run as plain
# daemons, one message each way must reach `delivered` (which only happens when
# the peer's receipt came back), plus a file transfer checked byte for byte.
#
# The pid list is deliberately global: an EXIT trap that reads a `local` array
# runs after the function scope is gone and silently kills nothing, leaving two
# daemons holding the ports.
TEST_PIDS=()
cleanup_test() {
  for p in "${TEST_PIDS[@]:-}"; do [ -n "$p" ] && kill "$p" 2>/dev/null || true; done
  for n in alice bob; do rm -f "$(pid_file "$n")"; done
}

cmd_test() {
  need_bin
  cmd_config
  if running alice || running bob; then
    die "stop the GUI first ('$0 down'); the test needs both ports"
  fi
  TEST_PIDS=()
  trap cleanup_test EXIT

  say "starting alice + bob daemons on $ALICE_ADDR / $BOB_ADDR"
  for n in alice bob; do
    : > "$(log_file "$n")"
    nohup "$BIN" run --config "$DIR/$n.toml" >> "$(log_file "$n")" 2>&1 &
    TEST_PIDS+=("$!")
    echo "$!" > "$(pid_file "$n")"
  done
  sleep 1.5

  local fail=0
  send_and_wait() {
    local from=$1 to=$2 body=$3
    say "$from -> $to"
    "$BIN" send --config "$DIR/$from.toml" --to "$to" --body "$body" \
      >/dev/null 2>>"$(log_file "$from")" ||
      { printf '[!] send %s -> %s failed\n' "$from" "$to" >&2; fail=1; return; }
    for _ in $(seq 1 60); do
      if "$BIN" inbox --config "$DIR/$from.toml" --limit 1 | grep -q delivered; then return; fi
      sleep 0.25
    done
    printf '[!] %s never saw a delivery receipt for "%s"\n' "$from" "$body" >&2
    fail=1
  }

  send_and_wait alice "$BOB_ID" "pair test: hello from alice"
  send_and_wait bob "$ALICE_ID" "pair test: hello from bob"

  # File: 4 KiB of random bytes, alice -> bob, compared by sha256.
  local src="$DIR/test-payload.bin"
  head -c 4096 /dev/urandom > "$src"
  say "alice -> bob: 4 KiB file"
  "$BIN" send --config "$DIR/alice.toml" --to "$BOB_ID" --file "$src" \
    >/dev/null 2>>"$(log_file alice)" ||
    { printf '[!] file send failed\n' >&2; fail=1; }
  local want; want="$(sha256sum "$src" | cut -d' ' -f1)"
  local got=""
  for _ in $(seq 1 80); do
    got="$(grep -rl . "$DIR/downloads-bob" 2>/dev/null | xargs -r sha256sum 2>/dev/null | awk -v w="$want" '$1==w{print $1; exit}')"
    [ -n "$got" ] && break
    sleep 0.25
  done
  if [ -n "$got" ]; then say "file arrived, sha256 matches"; else
    printf '[!] file did not arrive intact in %s/downloads-bob\n' "$DIR" >&2; fail=1
  fi

  echo
  for n in alice bob; do
    echo "--- $n inbox ---"
    "$BIN" inbox --config "$DIR/$n.toml" --limit 4 2>&1 | sed 's/^/  /'
  done
  [ "$fail" = 0 ] && say "PASS: both directions delivered" || die "FAIL: see above, then $DIR/*.log"
}

cmd_reset() {
  cmd_down
  rm -f "$DIR"/alice.db* "$DIR"/bob.db* "$DIR"/test-payload.bin
  rm -rf "$DIR"/downloads-alice "$DIR"/downloads-bob
  say "databases and downloads cleared (configs kept)"
}

cmd_logs() {
  local n="${1:-}"
  case "$n" in
    alice|bob) tail -n 60 "$(log_file "$n")" ;;
    "") for n in alice bob; do echo "--- $n ---"; tail -n 20 "$(log_file "$n")" 2>/dev/null || true; done ;;
    *) die "logs takes alice or bob" ;;
  esac
}

case "${1:-up}" in
  up)     cmd_up ;;
  down)   cmd_down ;;
  status) cmd_status ;;
  test)   cmd_test ;;
  config) cmd_config ;;
  reset)  cmd_reset ;;
  logs)   shift; cmd_logs "${1:-}" ;;
  -h|--help|help) sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) die "unknown command: $1 (up|down|status|test|config|reset|logs)" ;;
esac
